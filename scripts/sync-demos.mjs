// Bundles the demo sites built in "D:\MONARKA\Demo Webpage builder" into
// lib/demo-sites.generated.ts, so the Studio page can show them inside laptop
// mockups (iframe srcdoc). The demos get no URLs or pages of their own.
//
//   node scripts/sync-demos.mjs [sourceDir]
//
// Only demos listed in studio.demos.items (lib/i18n/es.ts) are bundled: that
// list is the allowlist of what's approved to publish. A folder that's in
// progress, or not cleared yet, stays out until it's added there.
//
// Each demo is read from <slug>/index.html, or <slug>/dist/index.html for
// built sites. Local stylesheets and scripts it references are inlined,
// because srcdoc pages can't load relative files.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE = process.argv[2] ?? "D:/MONARKA/Demo Webpage builder";
const OUT = path.join(ROOT, "lib/demo-sites.generated.ts");

const dict = await readFile(path.join(ROOT, "lib/i18n/es.ts"), "utf8");
const demosBlock = dict.slice(dict.indexOf("    demos: {"), dict.indexOf("    webDesign: {"));
const SLUGS = [...demosBlock.matchAll(/slug: "([^"]+)"/g)].map((m) => m[1]);

const isLocal = (ref) => !/^(?:[a-z]+:)?\/\//i.test(ref) && !ref.startsWith("data:");

async function inlineAssets(html, dir) {
  const parts = [];
  for (const m of html.matchAll(/<link\b[^>]*\brel=["']stylesheet["'][^>]*>/gi)) {
    const href = m[0].match(/\bhref=["']([^"']+)["']/i)?.[1];
    if (href && isLocal(href)) parts.push([m[0], `<style>\n${await readFile(path.join(dir, href), "utf8")}\n</style>`]);
  }
  for (const m of html.matchAll(/<script\b[^>]*\bsrc=["']([^"']+)["'][^>]*>\s*<\/script>/gi)) {
    if (!isLocal(m[1])) continue;
    const js = (await readFile(path.join(dir, m[1]), "utf8")).replace(/<\/script/gi, "<\\/script");
    parts.push([m[0], `<script>\n${js}\n</script>`]);
  }
  for (const [from, to] of parts) html = html.replace(from, () => to);
  return html;
}

const sites = {};
for (const slug of SLUGS) {
  let found = false;
  for (const rel of ["index.html", "dist/index.html"]) {
    const file = path.join(SOURCE, slug, rel);
    try {
      const html = await readFile(file, "utf8");
      sites[slug] = await inlineAssets(html, path.dirname(file));
      console.log(`bundled ${slug} from ${rel} (${(sites[slug].length / 1024).toFixed(1)} KB)`);
      found = true;
      break;
    } catch (err) {
      if (err.code !== "ENOENT") throw err;
    }
  }
  if (!found) console.warn(`skip ${slug}: listed on the site but no index.html in the builder folder`);
}

const body = `// AUTO-GENERATED by scripts/sync-demos.mjs from "${SOURCE}". Do not edit by hand.
// Loaded lazily (dynamic import) by components/sections/demo-gallery.tsx.

export const demoSites: Record<string, string> = ${JSON.stringify(sites, null, 2)};
`;
await writeFile(OUT, body);
console.log(`${Object.keys(sites).length}/${SLUGS.length} listed demos written to lib/demo-sites.generated.ts`);
