// Bundles the demo sites built in "D:\MONARKA\Demo Webpage builder" into
// lib/demo-sites.generated.ts, so the Studio page can show them inside laptop
// mockups (iframe srcdoc). The demos get no URLs or pages of their own.
//
//   node scripts/sync-demos.mjs [sourceDir]
//
// Re-run after editing the demos. The slugs below must match
// studio.demos.items in lib/i18n/{es,en}.ts.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const SOURCE = process.argv[2] ?? "D:/MONARKA/Demo Webpage builder";
const OUT = path.resolve(import.meta.dirname, "../lib/demo-sites.generated.ts");
const SLUGS = ["restaurant", "fitness", "saas", "studio", "awards-profile"];

const sites = {};
for (const slug of SLUGS) {
  const src = path.join(SOURCE, slug, "index.html");
  try {
    sites[slug] = await readFile(src, "utf8");
    console.log(`bundled ${slug} (${(sites[slug].length / 1024).toFixed(1)} KB)`);
  } catch {
    console.warn(`skip ${slug}: ${src} not found`);
  }
}

const body = `// AUTO-GENERATED by scripts/sync-demos.mjs from "${SOURCE}". Do not edit by hand.
// Loaded lazily (dynamic import) by components/sections/demo-gallery.tsx.

export const demoSites: Record<string, string> = ${JSON.stringify(sites, null, 2)};
`;
await writeFile(OUT, body);
console.log(`${Object.keys(sites).length}/${SLUGS.length} demos written to lib/demo-sites.generated.ts`);
